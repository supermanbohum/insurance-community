/**
 * 화면 아래에 붙는 요소가 홈 인디케이터(iOS)·제스처 바 위로 올라오게 하는 클래스.
 *
 * ⚠️ Tailwind는 이 파일도 소스로 훑는다(`content: ['./src/**\/*.{ts,tsx}']`)므로
 * 여기 적힌 임의값 클래스가 그대로 생성된다.
 *
 * 🔴 `max()`다. `calc(1rem + env(...))`가 아니다. **더하면 두 번 적용된다.**
 * 앱이 WebView를 이미 안전영역 안쪽에 배치해 두면, 웹이 또 inset만큼 더하는 순간
 * 버튼이 공중에 뜬다. max는 더하지 않고 둘 중 큰 값을 고르므로,
 *   - 안전영역이 0인 환경(데스크톱·안드로이드 대부분·앱이 이미 처리한 경우) → 1rem, 지금과 동일
 *   - 안전영역이 있는 환경(iOS 사파리 등)                                  → inset만큼만 올라감
 * 어느 쪽이든 **지금보다 아래로 내려가는 일은 없다.**
 *
 * ⚠️ 아직 실기기(iOS)에서 확인하지 못했다. 여기서 확인한 것은 "안전영역이 0인
 * 환경에서 동작이 바뀌지 않는다"까지다 - `env()`가 0이면 max가 1rem을 고르므로
 * 회귀가 불가능하다는 것이 근거이고, 실제 값이 얼마인지는 기기에서 봐야 한다.
 * 앱 WebView가 inset을 0으로 보고하는지 여부는 앱 세션 확인이 필요하다.
 *
 * 같은 목적의 선례: `BranchStickyActionBar`가 padding 쪽에 같은 방식을 쓴다
 * (`pb-[max(theme(spacing.3),env(safe-area-inset-bottom))]`). 두 곳이 다른 방식을
 * 쓰면 한쪽만 고쳐질 테니 방식을 맞춘다.
 */
export const STICKY_BOTTOM_SAFE = 'bottom-[max(1rem,env(safe-area-inset-bottom))]';
