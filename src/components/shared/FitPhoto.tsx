import { cn } from '@/lib/utils';
import { SafeBranchImage } from '@/components/shared/SafeBranchImage';

/**
 * 지점 사진을 카드 틀(`aspect-[4/3]`)에 **잘라내지도, 여백을 남기지도 않고** 넣는다.
 *
 * 오너 확정(2026-09-04):
 *   「전체사진이 보여야한다. 사진을 줄여서라도 다만, 줄인다고해서 공백이있으면안된다」
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 왜 `object-fit: fill` 인가 - 조건 셋을 동시에 만족하는 방법은 이것뿐이다
 * ─────────────────────────────────────────────────────────────────────────────
 * 고정 틀에 비율이 다른 사진을 넣을 때 선택지는 셋이고, **셋 다 만족시킬 수는 없다.**
 *
 *   cover    잘라낸다        → 전체가 안 보인다        ✗ 조건 1 위반
 *   contain  여백이 남는다   → 공백이 생긴다           ✗ 조건 3 위반
 *   fill     늘려서 맞춘다   → 전체 보임 + 공백 없음   ✓ 대가는 비율 왜곡
 *
 * 오너가 포기하지 않은 것이 「전체가 보인다」와 「공백 없음」이므로, 포기되는 것은
 * 「원래 비율 유지」다. 그래서 `fill` 이다.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 여기까지 온 경로 (같은 자리를 또 돌지 않도록 전부 남긴다)
 * ─────────────────────────────────────────────────────────────────────────────
 *   1차 cover(가운데)          카드는 찼지만 **가운데 한 줄만** 보였다 — 최초 신고
 *   2차 contain 통일           전체는 보이나 양옆에 띠 → 「짤린것처럼 보이잖아 꽉차지않고」
 *   3차 비율 자동(cover/contain) 대상 3장이 전부 극단이라 결국 2차와 같은 화면
 *   4차 cover + object-top     꽉 찼지만 아래가 잘렸다 → 「이게 아니다, 전체가 보여야 한다」
 *   5차 **fill** ← 지금        전체 보임 + 공백 없음. 대가는 왜곡.
 *
 * ⚠️ 근본 원인은 렌더링이 아니라 **사진 비율**이다. 실측(2026-09-04) 지금 홈에 뜨는
 *    대표사진이 세로로 2.3~5배 긴 홍보 이미지다(카톡·인스타용). 4:3 카드에 넣는 한
 *    어떤 방식도 온전하지 않다 — `fill` 이면 그만큼 가로로 눌린다.
 *    **가로로 찍은 사무실 실사진으로 바꾸면 왜곡이 거의 사라진다.** 그게 진짜 해결이다.
 */
export function FitPhoto({
  src,
  alt,
  sizes,
  priority,
  className,
}: {
  src: string;
  alt: string;
  sizes: string;
  priority?: boolean;
  /** 호버 확대 같은 카드별 효과를 넘길 때 쓴다. */
  className?: string;
}) {
  return (
    <SafeBranchImage
      src={src}
      alt={alt}
      sizes={sizes}
      priority={priority}
      // 🔴 cover(자름)도 contain(여백)도 아니다. 위 주석의 표를 보고 바꿔라.
      className={cn('object-fill', className)}
    />
  );
}
