import { cn } from '@/lib/utils';
import { SafeBranchImage } from '@/components/shared/SafeBranchImage';

/**
 * 지점 사진을 카드 틀(`aspect-[4/3]`)에 넣는다.
 * **꽉 채우되, 잘라내는 기준을 아래가 아니라 위로 둔다.** (오너 선택 2026-09-04)
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 여기까지 오는 데 두 번 틀렸다 - 남겨 둔다
 * ─────────────────────────────────────────────────────────────────────────────
 * 카드 틀은 4:3 고정인데 지점 사진은 비율이 제각각이다. 실측(2026-09-04, 홈 신규등록):
 * 대표사진 3장이 **전부 세로로 2.3~5배 긴 이미지**였다(카톡·인스타용 세로 홍보물).
 *
 *   1차 `object-cover` (가운데 기준)  카드는 꽉 차지만 **가운데 한 줄만** 보인다.
 *                                     오너 최초 신고가 이 상태였다.
 *   2차 `object-contain` 으로 통일     전체는 보이지만 폭이 좁아지고 양옆에 띠가 남는다.
 *                                     → 오너 지적 「짤린것처럼 보이잖아 꽉차지않고」. **내가 낸 회귀.**
 *   3차 비율 보고 cover/contain 자동    3장이 전부 극단이라 결국 전부 contain 이 됐다.
 *                                     2차와 화면이 같아 문제가 그대로였다.
 *   4차 **cover + object-position:top**  ← 지금. 실제 사진 3장으로 4가지를 렌더해
 *                                     오너가 직접 고른 방식이다.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 왜 「위쪽 기준」이 답인가
 * ─────────────────────────────────────────────────────────────────────────────
 * 세로로 긴 홍보 이미지는 **로고·회사명·핵심 문구가 위쪽에 몰려 있다.** 가운데를 기준으로
 * 자르면 그 전부가 사라지고 배경만 남는다. 위를 기준으로 자르면 **아래 여백이 잘리고
 * 중요한 부분이 살아남는다.** 일반 가로 사진(4:3·16:9)은 잘리는 양이 거의 없어
 * 가운데 기준과 사실상 차이가 없다.
 *
 * 🔴 늘려서 맞추지(`object-fit: fill`) 않는다. 세로 5배 사진을 4:3으로 누르면
 *    얼굴과 글자가 납작하게 찌그러진다 - 비교 화면에서 오너가 보고 배제한 안이다.
 *
 * ⚠️ 근본 원인은 렌더링이 아니라 **사진 비율**이다. 4:3 카드에 세로 5배 사진을 넣는 한
 *    어떤 방식도 온전하지 않다. 진짜 해결은 **대표사진을 가로 사무실 실사진으로 바꾸는 것**이고,
 *    그건 지점이 해야 한다. 이 컴포넌트는 그때까지 손실을 가장 줄이는 역할이다.
 */
export function FitPhoto({
  src,
  alt,
  sizes,
  priority,
  className,
}: {
  src: string;
  alt: string;
  sizes: string;
  priority?: boolean;
  /** 호버 확대 같은 카드별 효과를 넘길 때 쓴다. */
  className?: string;
}) {
  return (
    <SafeBranchImage
      src={src}
      alt={alt}
      sizes={sizes}
      priority={priority}
      // object-top 이 이 컴포넌트의 전부다. cover 는 원래대로 꽉 채운다.
      className={cn('object-cover object-top', className)}
    />
  );
}
